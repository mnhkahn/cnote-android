 function translate(source, fields = {}) {
  const localized = language === 'en' && Object.prototype.hasOwnProperty.call(english, source) ? english[source] : source;
  return localized.replace(/\{(\w+)\}/g, (placeholder, key) =>
   Object.prototype.hasOwnProperty.call(fields, key) ? String(fields[key]) : placeholder);
 }
